import subprocess
import tempfile
import os
from fastapi import FastAPI, UploadFile, File, HTTPException, Response

app = FastAPI(
    title="PDF to Text Converter API",
    description="A simple API to convert PDF files to Text format.",
    version="1.0.0"
)

# Resource exhaustion limit: 10MB max file size
MAX_FILE_SIZE = 10 * 1024 * 1024 

@app.post(
    "/convert",
    summary="Convert a PDF file to Text",
    description="Upload a PDF file to convert it into Text format.",
    responses={
        200: {"description": "Successfully converted PDF to text", "content": {"text/plain": {}}},
        400: {"description": "Bad Request - Invalid input or missing file"},
        500: {"description": "Internal Server Error - Conversion failed"},
    }
)
async def convert_pdf_to_text(file: UploadFile = File(...)):
    # 1. Validate file existence and extension
    if not file.filename or not file.filename.lower().endswith('.pdf'):
        raise HTTPException(status_code=400, detail="Invalid file. Please upload a PDF file.")

    # 2. Resource Exhaustion: Limit the size of the uploaded file
    # We read the content and check size before processing
    content = await file.read()
    if len(content) > MAX_FILE_SIZE:
        raise HTTPException(status_code=400, detail="File too large. Maximum size is 10MB.")

    # 3. Path Traversal Prevention: 
    # We do NOT use the user-provided filename in any path construction.
    # We use a secure temporary directory and hardcoded filenames.
    with tempfile.TemporaryDirectory() as tmpdir:
        # Use absolute paths generated by the OS for the temp directory
        input_path = os.path.join(tmpdir, "input.pdf")
        output_path = os.path.join(tmpdir, "output.txt")

        try:
            # Save the uploaded file to the temporary path
            with open(input_path, "wb") as f:
                f.write(content)

            # 4. Shell Injection Prevention:
            # subprocess.run is called with a list (shell=False by default).
            # This prevents shell injection as arguments are passed directly to the exec system call.
            # We also add a timeout to prevent Denial of Service via "PDF bombs" or hanging processes.
            subprocess.run(
                ["pdftotext", input_path, output_path],
                capture_output=True,
                text=True,
                check=True,
                timeout=30  # Prevent resource exhaustion/hanging
            )

            # Read the resulting text file
            if os.path.exists(output_path):
                with open(output_path, "r", encoding="utf-8") as f:
                    text_content = f.read()
                
                # Return as plain text response
                return Response(content=text_content, media_type="text/plain")
            else:
                raise Exception("Conversion failed to produce output.")

        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=500, detail="Conversion timed out.")
        except subprocess.CalledProcessError:
            # Error handling: Return 500 without leaking internal stderr/stack traces to the user
            raise HTTPException(status_code=500, detail="Internal Server Error - Conversion failed")
        except Exception:
            # Catch-all for other unexpected errors to prevent leaking internal details
            raise HTTPException(status_code=500, detail="Internal Server Error - Conversion failed")

if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=5000)