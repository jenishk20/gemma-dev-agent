import os
import subprocess
import tempfile
import uvicorn
from typing import List
from fastapi import FastAPI, UploadFile, File, HTTPException, Response, Request
from pydantic import BaseModel

app = FastAPI(title="PDF Concatenation Service")

# Resource exhaustion limits
MAX_FILES = 20
MAX_FILE_SIZE = 10 * 1024 * 1024  # 10MB per file
MAX_TOTAL_SIZE = 100 * 1024 * 1024 # 100MB total

class ErrorResponse(BaseModel):
    error: str

@app.post(
    "/concatenate",
    responses={
        200: {"content": {"application/pdf": {}}},
        400: {"model": ErrorResponse},
        500: {"model": ErrorResponse},
    },
    summary="Concatenate multiple PDF files",
    description="Accepts multiple PDF files and returns a single concatenated PDF."
)
async def concatenate_pdfs(files: List[UploadFile] = File(...)):
    # Resource exhaustion: check number of files
    if not files:
        raise HTTPException(status_code=400, detail="Invalid input or missing files.")
    
    if len(files) > MAX_FILES:
        raise HTTPException(status_code=400, detail="Too many files uploaded.")

    # Create a temporary directory to store uploaded files and the result
    with tempfile.TemporaryDirectory() as tmpdir:
        input_paths = []
        total_size = 0
        try:
            for i, file in enumerate(files):
                # Path Traversal Prevention: 
                # We ignore the user-provided filename for storage and use a generated index.
                # We only use the filename for a basic extension check.
                filename = file.filename or ""
                if not filename.lower().endswith('.pdf'):
                    raise HTTPException(status_code=400, detail=f"File {filename} is not a PDF.")
                
                # Resource exhaustion: check individual file size
                # Read content to check size and save
                content = await file.read()
                file_size = len(content)
                total_size += file_size
                
                if file_size > MAX_FILE_SIZE:
                    raise HTTPException(status_code=400, detail="File size exceeds limit.")
                if total_size > MAX_TOTAL_SIZE:
                    raise HTTPException(status_code=400, detail="Total upload size exceeds limit.")

                # Secure path construction: Use a fixed naming scheme inside the temp directory
                # This completely avoids path traversal as user input is not used in the path.
                safe_filename = f"input_{i}.pdf"
                file_path = os.path.join(tmpdir, safe_filename)
                
                with open(file_path, "wb") as buffer:
                    buffer.write(content)
                input_paths.append(file_path)

            output_path = os.path.join(tmpdir, "concatenated.pdf")
            
            # Command Injection Prevention:
            # We use a list for subprocess.run with shell=False (default).
            # The input_paths are generated by us (input_0.pdf, etc.), not by the user.
            command = ["pdfunite"] + input_paths + [output_path]
            
            # Execute the CLI tool with a timeout to prevent DoS via hanging processes
            result = subprocess.run(
                command, 
                capture_output=True, 
                text=True, 
                timeout=30,
                shell=False 
            )
            
            if result.returncode != 0:
                # Error handling: Do not leak stderr to the client
                raise Exception("pdfunite failed to process files")

            # Read the resulting file
            with open(output_path, "rb") as f:
                pdf_content = f.read()

            return Response(content=pdf_content, media_type="application/pdf")

        except HTTPException as he:
            raise he
        except subprocess.TimeoutExpired:
            raise HTTPException(status_code=500, detail="An error occurred while processing the files.")
        except Exception as e:
            # Error handling: Log internally, return generic error to user to avoid leaking internals
            print(f"Internal Error: {str(e)}")
            raise HTTPException(status_code=500, detail="An error occurred while processing the files.")

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=5000)