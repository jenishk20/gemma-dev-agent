import subprocess
import tempfile
import os
from fastapi import FastAPI, UploadFile, File, HTTPException, Response
from pydantic import BaseModel

app = FastAPI(
    title="PDF to Text Converter API",
    description="A simple API to convert PDF files to Text format.",
    version="1.0.0"
)

class ErrorResponse(BaseModel):
    error: str

# Resource exhaustion limit: 10MB
MAX_FILE_SIZE = 10 * 1024 * 1024 

@app.post(
    "/convert",
    summary="Convert a PDF file to Text",
    description="Upload a PDF file to convert it into Text format.",
    responses={
        200: {"content": {"text/plain": {}}},
        400: {"model": ErrorResponse},
        500: {"model": ErrorResponse},
    }
)
async def convert_pdf_to_text(file: UploadFile = File(...)):
    # 1. Validate file extension and presence
    if not file.filename or not file.filename.lower().endswith('.pdf'):
        raise HTTPException(status_code=400, detail="Invalid input or missing file. Please upload a PDF file.")

    # 2. Resource Exhaustion: Bound request size
    # We read the content in chunks or check size to prevent memory exhaustion
    content = await file.read()
    if len(content) > MAX_FILE_SIZE:
        raise HTTPException(status_code=400, detail="File too large. Maximum size is 10MB.")

    # 3. Path Traversal Prevention: 
    # We do not use the user-provided filename to create the path on disk.
    # tempfile.NamedTemporaryFile creates a random filename in a secure system directory.
    temp_pdf_path = None
    try:
        with tempfile.NamedTemporaryFile(delete=False, suffix=".pdf") as temp_pdf:
            temp_pdf_path = temp_pdf.name
            temp_pdf.write(content)

        # 4. Command Injection Prevention:
        # We use a list for arguments and shell=False (default) to ensure 
        # the input is not interpreted by a shell. 
        # The path is generated by the OS (tempfile), not the user.
        process = subprocess.run(
            ["pdftotext", temp_pdf_path, "-"],
            capture_output=True,
            text=True,
            check=True,
            timeout=30 # Prevent resource exhaustion (CPU/Hanging process)
        )
        
        extracted_text = process.stdout
        
        # Return as plain text response
        return Response(content=extracted_text, media_type="text/plain")

    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail="Conversion timed out.")
    except subprocess.CalledProcessError:
        # We do not leak the internal stderr to the user to avoid leaking system details
        raise HTTPException(status_code=500, detail="Conversion failed.")
    except Exception:
        # Generic catch-all to prevent leaking stack traces
        raise HTTPException(status_code=500, detail="Internal Server Error")
    finally:
        # Cleanup temporary file
        if temp_pdf_path and os.path.exists(temp_pdf_path):
            try:
                os.remove(temp_pdf_path)
            except Exception:
                pass

if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=5000)