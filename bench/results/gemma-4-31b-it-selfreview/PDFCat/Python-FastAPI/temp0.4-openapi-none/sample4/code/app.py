import os
import subprocess
import tempfile
import shutil
from typing import List
from fastapi import FastAPI, UploadFile, File, HTTPException, Response
import uvicorn

app = FastAPI(title="PDF Concatenation Service", version="1.0.0")

# Resource exhaustion limits
MAX_FILES = 50
MAX_FILE_SIZE = 10 * 1024 * 1024  # 10MB per file
MAX_TOTAL_SIZE = 100 * 1024 * 1024 # 100MB total

@app.post("/concatenate")
async def concatenate_pdfs(files: List[UploadFile] = File(...)):
    """
    Accepts multiple PDF files and returns a single concatenated PDF using pdfunite.
    """
    # 1. Resource Exhaustion: Bound number of files
    if not files:
        raise HTTPException(status_code=400, detail="Invalid input or missing files.")
    
    if len(files) > MAX_FILES:
        raise HTTPException(status_code=400, detail="Too many files uploaded.")

    # Create a temporary directory to store uploaded files and the result
    temp_dir = tempfile.mkdtemp()
    input_paths = []
    total_size = 0
    
    try:
        # Save uploaded files to the temp directory
        for i, file in enumerate(files):
            # 2. Resource Exhaustion: Bound file size
            # We read in chunks to avoid loading massive files into memory before checking size
            file_path = os.path.join(temp_dir, f"file_{i}.pdf")
            
            with open(file_path, "wb") as buffer:
                while True:
                    chunk = await file.read(65536)
                    if not chunk:
                        break
                    total_size += len(chunk)
                    if total_size > MAX_TOTAL_SIZE:
                        raise HTTPException(status_code=400, detail="Total upload size exceeds limit.")
                    buffer.write(chunk)
            
            # Check individual file size
            if os.path.getsize(file_path) > MAX_FILE_SIZE:
                raise HTTPException(status_code=400, detail="Individual file size exceeds limit.")
                
            input_paths.append(file_path)

        if len(input_paths) < 2:
            # If only one file is provided, just return that file
            if len(input_paths) == 1:
                with open(input_paths[0], "rb") as f:
                    content = f.read()
                return Response(content=content, media_type="application/pdf")
            raise HTTPException(status_code=400, detail="Invalid input or missing files.")

        output_path = os.path.join(temp_dir, "concatenated.pdf")
        
        # 3. Shell Injection Prevention: 
        # We use a list for subprocess.run and shell=False (default).
        # This avoids passing a string to a shell, preventing command injection.
        # The filenames are generated by us (file_0.pdf), not taken from user input.
        command = ["pdfunite"] + input_paths + [output_path]
        
        # Execute the CLI tool with a timeout to prevent DoS via hanging processes
        result = subprocess.run(
            command, 
            capture_output=True, 
            text=True, 
            timeout=30, 
            shell=False 
        )
        
        if result.returncode != 0:
            # 4. Error Handling: Do not leak stderr to the client
            raise Exception("pdfunite failed to process files")

        # Read the resulting PDF
        with open(output_path, "rb") as f:
            pdf_content = f.read()

        return Response(content=pdf_content, media_type="application/pdf")

    except subprocess.TimeoutExpired:
        raise HTTPException(status_code=500, detail="An error occurred while processing the files.")
    except HTTPException as he:
        raise he
    except Exception as e:
        # 4. Error Handling: Catch all and return documented 500 without leaking internals
        print(f"Internal Error: {e}") 
        raise HTTPException(status_code=500, detail="An error occurred while processing the files.")
    
    finally:
        # Cleanup temporary directory
        shutil.rmtree(temp_dir, ignore_errors=True)

if __name__ == "__main__":
    uvicorn.run(app, host="0.0.0.0", port=5000)